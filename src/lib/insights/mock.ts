function daysBefore(isoDate: string, days: number): string {
  const date = new Date(`${isoDate}T00:00:00Z`);
  date.setUTCDate(date.getUTCDate() - days);
  return date.toISOString().slice(0, 10);
}

/**
 * The cycle the feed shows. `quiet` returns the no-signal branch (V6) so the
 * empty state can be reviewed in the prototype.
 */
export function getCurrentCycle({ time = '06:00', quiet = false } = {}): Cycle {
  const date = todayInJakarta();
  const insights = quiet
    ? []
    : mockInsights.map(({ observedDaysAgo, ...insight }) => ({
        ...insight,
        observedOn: daysBefore(date, observedDaysAgo),
      }));
  return { date, time, insights, status: 'ok' };
}
